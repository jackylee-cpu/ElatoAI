#!/usr/bin/env python3
"""Turn a WAV file into one of the PCM tables the firmware plays at boot or sleep.

Neither sound can be a file: at boot nothing is mounted yet and no decoder has
started, and at sleep the drivers are already being torn down. Both ship as
plain int16 arrays in flash and go straight to I2S. That makes size the whole
design constraint -- a second of 24 kHz mono is 48 KB of the 2 MB app partition
-- which is why this script downmixes, resamples and trims rather than
embedding the source as-is.

    python3 tools/wav_to_sound.py boot  assets/boot-sound.wav
    python3 tools/wav_to_sound.py sleep assets/sleep-sound.wav
    python3 tools/wav_to_sound.py lowbattery assets/low-battery.wav
    python3 tools/wav_to_sound.py otaupdate assets/ota-update.wav

Writes src/BootSoundData.cpp / src/SleepSoundData.cpp / src/LowBatterySoundData.cpp /
src/OtaUpdateSoundData.cpp. Re-run whenever a source WAV changes; the generated
files are committed, so a normal build needs neither Python nor the WAVs.
"""

import argparse
import pathlib
import sys
import wave

import numpy as np

# Per-sound defaults. The rates are not a house style, they are what each
# recording needs: the boot chord is a few sine-ish partials with 99.9% of its
# energy below 4 kHz, so 8 kHz of bandwidth throws away nothing audible, while
# the sleep sound is chiptune and carries a quarter of its energy between 8 and
# 11 kHz -- at 16 kHz it audibly dulls, so it pays for the extra 50%.
SOUNDS = {
    "boot": dict(rate=16000, symbol="kBootSound", out="BootSoundData.cpp"),
    "sleep": dict(rate=24000, symbol="kSleepSound", out="SleepSoundData.cpp"),
    # Speech: 16 kHz keeps it intelligible at a third less flash than 24 kHz.
    "lowbattery": dict(rate=16000, symbol="kLowBatterySound", out="LowBatterySoundData.cpp"),
    "otaupdate": dict(rate=16000, symbol="kOtaUpdateSound", out="OtaUpdateSoundData.cpp"),
}

# Where to cut the reverb tail, relative to the loudest sample. The tail decays
# smoothly for well over a second below this, and every 100 ms of it is 3.2 KB
# of flash and 100 ms of boot the device spends not connecting to wifi.
DEFAULT_TAIL_DB = -42.0

FADE_IN_S = 0.005   # against a source that starts mid-waveform
FADE_OUT_S = 0.150  # long enough that the trim is a decay, not a cut
PEAK = 0.89         # leaves headroom for the playback gain's rounding


def read_wav(path):
    with wave.open(str(path)) as w:
        if w.getsampwidth() != 2:
            sys.exit(f"{path}: need 16-bit PCM, got {8 * w.getsampwidth()}-bit")
        rate, channels = w.getframerate(), w.getnchannels()
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2")
    samples = pcm.reshape(-1, channels).astype(np.float64).mean(axis=1)
    return samples, rate


def resample(x, src_rate, dst_rate, taps=32):
    """Windowed-sinc resampling, with the anti-alias cutoff at the new Nyquist.

    Written out rather than pulled from scipy so that regenerating the table
    needs nothing but numpy.
    """
    if src_rate == dst_rate:
        return x
    ratio = dst_rate / src_rate
    cutoff = min(1.0, ratio)  # relative to the source Nyquist
    n_out = int(round(len(x) * ratio))
    # Source position of each output sample, and the integer taps around it.
    centers = np.arange(n_out) / ratio
    base = np.floor(centers).astype(np.int64)
    offsets = np.arange(-taps + 1, taps + 1)
    idx = base[:, None] + offsets[None, :]
    t = (centers[:, None] - idx) * cutoff
    kernel = np.sinc(t) * np.blackman(2 * taps)[None, :] * cutoff
    kernel /= kernel.sum(axis=1, keepdims=True)
    padded = np.pad(x, taps)
    return (padded[idx + taps] * kernel).sum(axis=1)


def trim_tail(x, rate, tail_db):
    """Drop everything after the signal's last excursion above `tail_db`."""
    threshold = np.abs(x).max() * 10 ** (tail_db / 20.0)
    loud = np.flatnonzero(np.abs(x) > threshold)
    if len(loud) == 0:
        return x
    return x[: min(len(x), loud[-1] + int(FADE_OUT_S * rate))]


def shape(x, rate):
    """Remove DC, fade both ends, normalise. Order matters: the fades have to
    act on a signal already centred on zero, or they fade towards the offset."""
    x = x - x.mean()
    n_in, n_out = int(FADE_IN_S * rate), int(FADE_OUT_S * rate)
    if n_in:
        x[:n_in] *= 0.5 * (1 - np.cos(np.linspace(0, np.pi, n_in)))
    if n_out:
        x[-n_out:] *= 0.5 * (1 + np.cos(np.linspace(0, np.pi, n_out)))
    peak = np.abs(x).max()
    return x * (PEAK * 32767.0 / peak) if peak else x


def emit(path, samples, rate, source, tail_db, symbol):
    pcm = np.clip(np.round(samples), -32768, 32767).astype(np.int64)
    lines = [
        "// Generated by tools/wav_to_sound.py -- do not edit.",
        f"//   source: {source}",
        f"//   {rate} Hz mono, {len(pcm)} frames ({len(pcm) / rate:.2f} s), "
        f"tail trimmed at {tail_db:g} dBFS",
        "",
        '#include "SoundData.h"',
        "",
        # The rate lives here and not in the header so that re-running this
        # script with --rate cannot leave the two disagreeing.
        f"const int {symbol}Rate = {rate};",
        f"const unsigned {symbol}Frames = {len(pcm)};",
        "",
        "// const, so the linker leaves it in flash and I2S can read it in place.",
        f"const int16_t {symbol}Pcm[] = {{",
    ]
    for i in range(0, len(pcm), 16):
        lines.append("    " + ",".join("%d" % v for v in pcm[i : i + 16]) + ",")
    lines += ["};", ""]
    path.write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=sorted(SOUNDS))
    ap.add_argument("wav", type=pathlib.Path)
    ap.add_argument("--rate", type=int)
    ap.add_argument("--tail-db", type=float, default=DEFAULT_TAIL_DB)
    args = ap.parse_args()

    sound = SOUNDS[args.kind]
    rate = args.rate or sound["rate"]
    dest = pathlib.Path(__file__).resolve().parents[1] / "src" / sound["out"]

    samples, src_rate = read_wav(args.wav)
    out = shape(trim_tail(resample(samples, src_rate, rate), rate, args.tail_db), rate)
    emit(dest, out, rate, args.wav.name, args.tail_db, sound["symbol"])

    print(f"{args.kind}: {args.wav.name} {len(samples) / src_rate:.2f}s @ {src_rate} Hz "
          f"-> {len(out) / rate:.2f}s @ {rate} Hz mono, "
          f"{2 * len(out) / 1024:.0f} KB of flash -> src/{sound['out']}")


if __name__ == "__main__":
    main()
